// Import only licensed audio, convert OGG to iOS-compatible PCM WAV, and embed browser buffers.
// node scripts/build-sfx-assets.cjs /path/to/new-platformer /path/to/interface
// With no arguments, regenerate only sfx-data.js from the bundled WAVs.
const fs = require('node:fs');
const path = require('node:path');
const { execFileSync } = require('node:child_process');
const dir = path.join(__dirname, '../PrehistoricBeastmaster/Resources/game');
const audioDir = path.join(dir, 'audio/sfx');
const manifest = JSON.parse(fs.readFileSync(path.join(audioDir, 'manifest.json'), 'utf8'));
const packs = { platformer: process.argv[2], interface: process.argv[3] };
const files = {};
for (const [name, entry] of Object.entries(manifest.files)) {
    const destination = path.join(audioDir, name);
    if (packs[entry.pack]) execFileSync('/usr/bin/afconvert', ['-f', 'WAVE', '-d', 'LEI16', path.join(packs[entry.pack], entry.original), destination]);
    let bytes = fs.readFileSync(destination);
    if (bytes.toString('ascii', 0, 4) !== 'RIFF' || bytes.toString('ascii', 8, 12) !== 'WAVE') throw new Error(`Invalid WAV: ${name}`);
    let format, pcm;
    for (let offset = 12; offset + 8 <= bytes.length;) {
        const tag = bytes.toString('ascii', offset, offset + 4), size = bytes.readUInt32LE(offset + 4);
        if (tag === 'fmt ') format = bytes.subarray(offset + 8, offset + 8 + size);
        if (tag === 'data') pcm = Buffer.from(bytes.subarray(offset + 8, offset + 8 + size));
        offset += 8 + size + (size % 2);
    }
    if (!format || !pcm || format.readUInt16LE(14) !== 16 || ![1, 65534].includes(format.readUInt16LE(0))) throw new Error(`Expected 16-bit PCM: ${name}`);
    if (format.readUInt16LE(0) === 65534 && format.readUInt32LE(24) !== 1) throw new Error(`Non-PCM WAV: ${name}`);
    let peak = 0;
    for (let offset = 0; offset < pcm.length; offset += 2) peak = Math.max(peak, Math.abs(pcm.readInt16LE(offset)));
    if (!peak) throw new Error(`Silent sample: ${name}`);
    // Consistent headroom before per-cue mixing; some source clicks are otherwise barely audible.
    for (let offset = 0; offset < pcm.length; offset += 2) pcm.writeInt16LE(Math.round(pcm.readInt16LE(offset) * 27852 / peak), offset);
    // A standard compact PCM header avoids platform-specific extensible WAV metadata.
    const header = Buffer.alloc(44);
    header.write('RIFF', 0); header.writeUInt32LE(pcm.length + 36, 4); header.write('WAVEfmt ', 8);
    header.writeUInt32LE(16, 16); header.writeUInt16LE(1, 20); format.copy(header, 22, 2, 16);
    header.write('data', 36); header.writeUInt32LE(pcm.length, 40);
    bytes = Buffer.concat([header, pcm]);
    fs.writeFileSync(destination, bytes);
    files[name] = bytes.toString('base64');
}
fs.writeFileSync(path.join(dir, 'sfx-data.js'), '// Generated by scripts/build-sfx-assets.cjs. Kenney CC0; see audio/sfx/CREDITS.md.\nwindow.GameSfxAssets = ' + JSON.stringify({ files, cues: manifest.cues }) + ';\n');
console.log(`Bundled ${Object.keys(files).length} WAV files and ${Object.keys(manifest.cues).length} sound cues.`);
