// Source-contract checks only. Native Swift behavior is exercised by
// test-payment-flow.cjs on macOS; these checks do not claim an iOS build passed.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const manager = fs.readFileSync(path.join(root, 'PrehistoricBeastmaster/Payment/StoreKitManager.swift'), 'utf8');
const service = fs.readFileSync(path.join(root, 'PrehistoricBeastmaster/Payment/BillingService.swift'), 'utf8');
const shellConfig = fs.readFileSync(path.join(root, 'PrehistoricBeastmaster/Config/ShellConfig.swift'), 'utf8');
const infoPlist = fs.readFileSync(path.join(root, 'PrehistoricBeastmaster/Info.plist'), 'utf8');
assert.doesNotMatch(service + shellConfig + infoPlist, /ShellPaymentApiToken|paymentApiToken/);
assert.ok((service.match(/try await paymentAuthorization\(\)/g) ?? []).length >= 3,
  'Order creation, confirmation and status recovery must use the player session');
assert.ok(service.includes('request.setValue("Bearer \\(authorization)"'));
assert.ok((service.match(/SecureAPIURLSession\.shared\.data/g) ?? []).length >= 2,
  'Authenticated payment GET and POST requests must reject redirects');
assert.match(service, /let appAccountToken: UUID/);
assert.match(service, /let token = try requireAppAccountToken\(responseData\)/);
assert.match(service, /APP_ACCOUNT_TOKEN_MISSING/);
assert.match(service, /INVALID_APP_ACCOUNT_TOKEN/);
assert.match(manager, /var appAccountToken: UUID\?/);
assert.match(manager, /appAccountToken: order\.appAccountToken/);
assert.match(manager, /guard let token = context\.appAccountToken/);
assert.match(manager, /let options: Set<Product\.PurchaseOption> = \[\.appAccountToken\(token\)\]/);
const purchase = manager.slice(manager.indexOf('    private func purchase('), manager.indexOf('    private func handlePurchaseResult('));
assert.doesNotMatch(purchase, /appAccountToken\(for:|sha256Hex|uuidHex/);
assert.match(manager, /transaction\.appAccountToken != expectedToken/);
const confirmation = manager.slice(manager.indexOf('    private func confirm('), manager.indexOf('    static func isTransientDeliveryCode('));
const serverConfirmation = confirmation.slice(confirmation.indexOf('let confirmation = try await backend.confirmPurchase('));
assert.match(serverConfirmation, /backend\.confirmPurchase\(/);
assert.ok(serverConfirmation.indexOf('guard confirmation.consume') < serverConfirmation.indexOf('recordCompleted(transaction'));
assert.ok(serverConfirmation.indexOf('recordCompleted(transaction') < serverConfirmation.indexOf('removeStoredContext(context)'));
assert.ok(serverConfirmation.indexOf('recordCompleted(transaction') < serverConfirmation.indexOf('scheduleCompletedFinish(transaction)'));
assert.ok(serverConfirmation.indexOf('recordCompleted(transaction') < serverConfirmation.indexOf('listener?.onSuccess('));
assert.doesNotMatch(serverConfirmation, /await transaction\.finish/);
const migration = confirmation.slice(confirmation.indexOf('if ProductCatalog.contains(transaction.productID)'), confirmation.indexOf('let context = findContext'));
assert.match(migration, /AnalyticsEventCoordinator\.hasLegacyVerifiedPurchase/);
assert.doesNotMatch(migration, /onSuccess|removeStoredContext|createPlayOrder|confirmPurchase/);
assert.match(confirmation, /sdkOrderId: context\.sdkOrderId/);
assert.match(confirmation, /signedTransaction: jws/);
assert.doesNotMatch(confirmation, /createPlayOrder|\.purchase\(/);
const failed = confirmation.slice(confirmation.indexOf('catch let error'));
assert.doesNotMatch(failed, /removeStoredContext|transaction\.finish/);
const deliveryFailure = manager.slice(manager.indexOf('    private func deliveryFailed('), manager.indexOf('    private func scheduleDeliveryRecovery('));
assert.doesNotMatch(deliveryFailure, /removeStoredContext|transaction\.finish/);
const completed = confirmation.slice(confirmation.indexOf('if ProductCatalog.contains(transaction.productID)'), confirmation.indexOf('guard !confirmingTokens.contains'));
assert.match(completed, /completed\.productId == transaction\.productID/);
assert.match(completed, /completed\.appAccountToken == transaction\.appAccountToken/);
assert.match(completed, /transactionId == token/);
assert.match(completed, /finishCompletedTransaction\(transaction/);
assert.match(service, /responseData\?\.bool\("consume", false\) \?\? false/);
console.log('iOS account-binding source contracts passed (static, not a native build).');
